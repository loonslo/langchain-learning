def drill(topic: str = "") -> None:
    """打印面试速查。传入关键词只看匹配的组，不传看全部。"""
    hit = 0
    for group, items in CHEATSHEET.items():
        if topic and topic not in group:
            continue
        hit += 1
        print(f"\n{'='*60}\n【{group}】共 {len(items)} 条\n{'='*60}")
        for i, it in enumerate(items, 1):
            print(f"\nQ{i}. {it['q']}")
            print(f"  💬 {it['a']}")
            print(f"  ↳ 原理：{it['why']}")
            print(f"  ↳ 代码：{it['day']}")
    if topic and not hit:
        print(f"没有匹配「{topic}」的组。可选：{list(CHEATSHEET.keys())}")


if __name__ == "__main__":
    kw = sys.argv[1] if len(sys.argv) > 1 else ""
    drill(kw)
    total = sum(len(v) for v in CHEATSHEET.values())
    print(f"\n{'-'*60}\n共 {total} 条护城河面试话术。核心叙事：可测 / 可评 / 可回归 / 可上线。")


