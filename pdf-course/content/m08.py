"""第 8 章　把对话变成业务契约"""
import dia
from comp import (P, E, C, SIDE, KEYPOINT, VERIFY, TRAP, CHECKLIST, UL, OL,
                  CODE, TABLE, HOOK, FIG, PAGEWRAP, CHAPTER, H3, H4,
                  RUN, TASK)


def chapter():
    p = []
    p.append(CHAPTER(8, "把对话变成业务契约",
                     "用户说的话是自由的，业务流程要的是确定的参数。"
                     "这一章解决的就是这道缝：怎么从一句话里拿到能执行的东西。",
                     "ch8"))

    p.append(P(
        "用户说：「我上周买的那个东西怎么还没到，有点急。」",
        "这句话里藏着三个业务信息：他想查物流、大概是一周内的订单、"
        "情绪偏着急需要优先处理。"
        "但" + E("没有订单号") + "——而查物流的接口要的就是订单号。"))
    p.append(FIG(dia.flow([
        ("自由的一句话", "我上周买的那个东西怎么还没到"),
        ("意图 + 槽位", "查物流，缺订单号"),
        ("可执行的请求", "接口要的参数齐了"),
    ], note="中间那一层就是这一章要建的东西："
            "把自由文本翻译成结构化的、可执行的请求，也就是「业务契约」。"),
        "中间那一层，就是把对话变成业务契约的地方"))

    p.append(SIDE("一个重要的交代：代码换了新项目",
                  P("这一段的实现代码换到了" + C("enterprise_support")
                    + "（由 " + C("tools/materialize_enterprise_day.py") + " 还原）。"
                    "它不是第 6 章那个 " + C("customer_support") + " 的延续，"
                    "而是一条" + E("新的产品线") + "。"),
                  P("为什么要另起：第 6 章的产品重点是「知识问答 + 工具 + 安全边界」，"
                    "这一段重点是「对话如何驱动业务状态」。"
                    "把两者塞进一套代码会让职责混乱。"
                    "在真实项目里，这是常见的做法——"
                    + E("不同的问题用不同的服务，通过协议协作") + "（第 10 章会讲怎么协作）。")))

    # ── 8.1 ──
    p.append(H3("8.1　意图识别：先把「他想干什么」定下来"))
    p.append(P(
        "第一步，是把所有可能的意图列成一个固定清单——"
        "不是让模型自由发挥，而是从有限的选项里选一个。"))
    p.append(FIG(dia.cards([
        ("查订单", "问订单状态或物流；需要的参数：订单号"),
        ("申请退款", "要求退钱；需要的参数：订单号 + 退款原因"),
        ("咨询政策", "问规则，走知识库；需要的参数：问题本身"),
        ("其他 / 未知", "不属于上面任何一类；没有参数"),
    ], cols=2),
        "四个意图，每个都能对应一段确定的处理代码"))
    p.append(P("枚举而不是让模型自由描述，理由在这里："
               + E("枚举之后，每一个意图都能对应一段确定的处理代码。") +
               "自由描述则无法映射到代码。"))
    p.append(SIDE("白话：few-shot（少样本）",
                  P("在提示词里给几个「输入 → 输出」的例子，让模型照着格式做。"
                    "比如给出三句用户的话和它们对应的意图，模型就会模仿这个判断方式。"),
                  P("它比「解释规则」有效，因为模型从例子中学格式，比从描述中猜格式更准。"
                    "代价是提示词变长，占上下文。")))
    p.append(P("清单里还要留一个出口：" + E("未知") + "。"
               "如果强制模型在「查订单/退款/咨询」里选一个，"
               "遇到「你们公司在哪里」这种问题时，它会被迫选一个错误的意图，"
               "然后触发一个错误的业务动作。"))
    p.append(FIG(dia.compare(
        ("强制三选一", [
            "「你们公司在哪里」被迫选一个错意图",
            "接着触发一个错误的业务动作",
        ]),
        ("留一个「未知」出口", [
            "模型有地方说「我不确定」",
            "未知走转人工，不动业务状态",
        ]),
        note="留一个「其他/未知」类别，模型才有地方说「我不确定」；"
             "没有出口的强制分类，是把不确定性变成了错误动作。"),
        "分类清单少一个出口，不确定性就会变成错误动作"))

    # ── 8.2 ──
    p.append(H3("8.2　槽位：缺什么就问什么"))
    p.append(P(
        "识别出意图之后，下一步是抽出执行这个意图需要的参数——"
        "这些参数在对话系统里叫" + E("槽位（slot）") + "。"
        "参数齐全就直接执行，缺参数就追问，用户补上之后从上次的状态继续。"))
    p.append(FIG(dia.loop([
        ("抽槽位", "对照意图，看还缺哪些参数"),
        ("追问", "只问缺的那一项"),
    ], center="补上的参数留在状态里，下一轮接着用",
        note="这一节的重点不是「怎么抽」，而是「抽不到的时候怎么办」。"),
        "缺参数就追问，补上的参数留在状态里"))
    p.append(FIG(dia.compare(
        ("每轮都重新开始", [
            "第二轮丢掉「上周买的」",
            "一直问「请问订单号是多少」",
        ]),
        ("从上次的状态继续", [
            "已经拿到的参数还在状态里",
            "下一轮只补缺的那一项",
        ]),
        note="用户回一句话就重新识别意图、重新抽槽位，对话会卡在原地打转；"
             "状态记的是「当前走到哪一步」，系统才知道这一句是在回答哪个问题。"),
        "追问最容易做错的地方：把已经拿到的信息丢掉"))
    p.append(P("把这段对话走一遍就清楚了：用户说「我上周买的那个东西还没到，有点急」，"
               "系统认出意图是查物流，抽到了「上周」这个时间，缺订单号，"
               "于是只回一句「麻烦给一下订单号，我马上查」。"
               "用户补上一句「A12345，麻烦快一点」——这一轮系统沿用状态里已有的「查物流」和「上周」，"
               "只把订单号补上，参数齐了就直接调物流接口。"
               "如果第三轮用户问「那能退吗」，订单号还在状态里，不用再问一遍。"))

    # ── 8.3 ──
    p.append(H3("8.3　让模型稳定输出 JSON，并且只修一次"))
    p.append(P(
        "意图和槽位最终要以结构化数据的形式交给程序，也就是 JSON。"
        "但模型输出 JSON 有两个常见毛病：格式对不上（多写了一段解释、少了引号），"
        "以及字段值不符合约束（该是数字的地方给了「大约五天」）。"))
    p.append(FIG(dia.flow([
        ("模型输出", "格式或取值可能不对"),
        ("按 schema 校验", "不通过就进入修复"),
        ("一次修复", "还不行就明确失败"),
    ], note="最多两次：原始输出加一次修复。第二次仍不通过就直接抛错，"
            "不再调用模型——异常由上层接住，走人工处理分支。"),
        "校验加一次受控修复，第二次不过就认输"))
    p.append(CODE([
        "text = llm.invoke(EXTRACT_PROMPT.format(question=question)).content",
        "last_err = None",
        "for attempt in range(2):            # 1 次原始 + 最多 1 次修复",
        "    try:",
        "        return Ticket(**json.loads(text))",
        "    except (json.JSONDecodeError, ValidationError) as e:",
        "        last_err = e",
        "        if attempt == 1:            # 已经是最后一次，不再白调一次模型",
        "            break",
        "        text = llm.invoke(f'上次输出不符合要求（{e}），请只输出合法 JSON：\\n{text}').content",
        "",
        "# 两次都不合格：明确失败，由上层接住并转人工",
        "raise ExtractionFailed(f'两次都未能得到合法 JSON：{last_err}')",
    ]))
    p.append(KEYPOINT("「一次修复」而不是「循环重试」——"
                      "修不好通常说明问题在提示词或模型能力，"
                      "再试一百次也是同样的结果，只是把延迟和账单一起放大。"
                      "明确失败，把问题交回给能改提示词的人。"))
    p.append(P("这里还有一件事要说清：" + E("抛异常本身不等于「已经交给人工」")
               + "。它只是把控制权交回调用方。"
                 "真正转人工靠的是上层接住异常之后做的事——"
                 "给用户一句「这个问题我处理不了，已经记下来了」，"
                 "同时把原始输入和失败原因落一条记录，等人来看。"
                 "少了上层这一段，异常只会变成用户看到的一个报错页。"))
    p.append(VERIFY(P("故意给模型一个很难结构化的问题（比如含糊到没有答案），"
                      "看它是明确失败、还是编一个看起来合理的 JSON。"
                      "编出来的 JSON 最难发现，因为它能通过格式校验。"
                      "顺便数一下模型的调用次数——应当是 1 次或 2 次；"
                      "出现 3 次，说明修复循环多跑了一轮。")))

    # ── 8.4 ──
    p.append(H3("8.4　把四件事串成工作流"))
    p.append(P(
        "最后一节把前面几节串成一条完整的工作流，"
        "并且每一步的状态都能跨轮恢复。"))
    p.append(FIG(dia.states([
        ("分类", "识别意图", "认出"),
        ("补参", "检查槽位，缺则追问", "齐全"),
        ("执行", "调用业务动作", "出错"),
        ("转接", "开人工工单，带上下文", ""),
    ], note="每一格的失败出口都通向转人工：意图识别不出、用户连续两次不配合、"
            "执行业务动作失败，都开一张带着上下文的人工工单。"),
        "分类 → 补参 → 执行 → 转接，失败都汇到转人工"))
    p.append(P("这一节留下的一条线是："
               + E("意图不明或缺参数时，不执行有副作用的动作。")
               + "多问一句的代价是慢一拍；猜错的代价是退错钱。"))
    p.append(TRAP(P("让模型「聪明地推断」缺失的参数。"
                    "比如用户说「退了我昨天那个」，模型推断出一个订单号——"
                    "猜对了没人夸，猜错了是资金事故。"
                    "缺参数就追问，推断出来的值没有依据。")))

    p.append(H4("这一章的产出物"))
    p.append(P("一个不会在意图不明或缺参时误执行副作用的客服 Agent："
               "意图枚举、槽位抽取与跨轮追问、稳定 JSON 输出、"
               "可恢复的显式工作流。代码位置："
               + C("chapters/part9-enterprise-infra-optional/9.1-9.4")
               + " 的 " + C("enterprise-support/") + "。"))
    p.append(RUN([
        ("代码位置", C(".build/enterprise/<chapter>/enterprise-support/") + "，由 "
                      + C("tools/materialize.py enterprise <chapter>") + " 还原"),
        ("工作目录", "还原出来的目录"),
        ("额外依赖", "无"),
        ("执行命令", C("python tools/materialize.py enterprise 9.4-intent-workflow")),
        ("预期输出", "意图分类、槽位追问、稳定的 JSON 输出、可恢复的工作流"),
        ("常见失败", "缺参数时误执行了有副作用的动作；"
                      "JSON 修复循环多跑了一轮，模型被白调一次"),
        ("完成证据", "故意问一个含糊到没有订单号的问题，它追问，而不是猜一个"),
    ]))
    p.append(TASK("把 8.1 的意图清单删掉「未知」那一项，再问一句「你们公司在哪里」。"
                  "看它被逼着选了哪个意图、触发了什么动作。"
                  "这一次观察，就是「留一个出口」这条规矩的由来。"))
    p.append(CHECKLIST([
        "意图枚举，以及清单末尾那个「未知」出口的作用；",
        "槽位抽取，以及追问时保留已有参数的理由；",
        "「一次修复」而不是「循环重试」的取舍；",
        "「意图不明时不执行副作用」这条线；",
        "这一章的产品和第 6 章的产品分成两个服务的理由。",
    ]))

    p.append(HOOK("现在对话能被翻译成确定的业务请求了。但请求要落到真实的数据上："
                  "订单在 PostgreSQL 里、热点数据要缓存、"
                  "模型可能跑在你自己的显卡上。"
                  "第 9 章把这些真实的企业基础设施接上。"))
    return PAGEWRAP("8　把对话变成业务契约", "".join(p))
