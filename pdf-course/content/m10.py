"""第 10 章　让 Agent 之间协作：MCP 与 A2A"""
import dia
from comp import (P, E, C, SIDE, KEYPOINT, VERIFY, TRAP, CHECKLIST, UL, OL,
                  CODE, TABLE, HOOK, FIG, PAGEWRAP, CHAPTER, H3, H4,
                  RUN, TASK)


def chapter():
    p = []
    p.append(CHAPTER(10, "让 Agent 之间协作：MCP 与 A2A",
                     "最后一步，把「一个 Agent 会用工具」升级成"
                     "「多个 Agent 在身份和权限约束下互相委托任务」。",
                     "ch10"))

    p.append(P(
        "真实的公司里，客服系统和订单系统通常是两个团队维护的两套服务。"
        "客服 Agent 需要查订单，但它不该直接连订单系统的数据库——"
        "那意味着客服团队要拿到订单库的权限，而且订单系统改结构时客服就会坏。"))
    p.append(P("更常见的做法是把「查这个订单」当成一个任务，委托给订单 Agent："
               "订单 Agent 在自己的权限范围内处理，把结果返回。"
               "这一章讲的就是这件事的两套协议：MCP 和 A2A。"))
    p.append(FIG(dia.compare(
        ("MCP：Agent 接工具", [
            "把工具做成标准服务",
            "任何支持 MCP 的客户端都能接上",
            "关系是「我让它做一件事」",
        ]),
        ("A2A：Agent 接 Agent", [
            "对方不是被动工具，而是能自己决策的智能体",
            "有自己的状态和生命周期",
            "关系是「我把任务交给它，它自己想办法」",
        ]),
        note="两者不互相替代：一个解决怎么用工具，一个解决怎么和另一个 Agent 协作。"),
        "MCP 管工具接入，A2A 管 Agent 之间协作"))

    # ── 10.1 ──
    p.append(H3("10.1　MCP 鉴权：工具不是随便谁都能用"))
    p.append(P(
        "第 4 章写了 MCP 服务器，但没有讲权限。这一段补上这一块："
        "一个暴露了企业工具的服务，要能判断这次调用是谁发起的、他有没有权限。"))
    p.append(FIG(dia.cards([
        ("audience", "这个令牌是发给谁的。防住令牌被转发到别的服务上使用"),
        ("scope", "这个令牌允许做什么。防住只能查订单的令牌被拿去执行退款"),
        ("最小权限", "只给完成当前任务所需的权限。防住一个服务被攻破导致全线失守"),
    ], cols=3, note="三条一起用：令牌有归属、有范围、有多小给多小。"),
        "鉴权的三个概念，各防住一类越权"))
    p.append(P("scope 里最容易漏的是读操作。"
               + E("「查询」看着没有破坏性，但它可能把别的客户的数据读出来")
               + "——一次跨租户的读和一次跨租户的写，泄露的后果是一样的。"
                 "所以读工具同样要在 scope 和租户边界上校验，"
                 "只是它不必再等一次人工审批。"))
    p.append(FIG(dia.compare(
        ("读工具", [
            "查订单、查知识库这类动作",
            "不改数据，但可能读到别的租户的行",
            "仍要校验：这个调用方能读哪些租户的数据",
        ]),
        ("写工具", [
            "退款、改地址这类动作",
            "写错了会改变现实世界的状态",
            "在上面那道校验之上，再加人工审批",
        ]),
        note="读操作不是「直接放行」，只是它怕的东西不一样："
             "写操作怕改错，读操作怕看到不该看的。"),
        "读和写都要授权，区别在额外要不要人拍板"))
    p.append(TRAP(P("用一个万能令牌，所有服务共用一份高权限凭据。"
                    "任何一个环节泄露，攻击者拿到的就是全部权限。"
                    "每个调用方一个令牌、每个令牌只够它自己用，泄露的代价就被限制在一处。")))

    # ── 10.2 ──
    p.append(H3("10.2　A2A：把任务当成一等公民"))
    p.append(P(
        "A2A 和普通接口调用最大的区别是：" + E("任务是有状态的、有生命周期的。") +
        "调用方发出任务后，任务可能立刻完成，也可能需要对方补充信息，还可能中途失败。"))
    p.append(FIG(dia.cards([
        ("Agent Card", "一张能力说明书：能做什么、需要什么输入、有哪些技能。"
                       "调用方靠它发现能力，不靠口头约定"),
        ("任务状态机", "从已提交到处理中，再到已完成 / 需要补充信息 / 失败，"
                       "每个状态都有明确定义"),
        ("幂等", "同一个任务重复提交，只执行一次"),
    ], cols=3, note="三样东西合起来，任务才成为协议里的一等公民。"),
        "任务有身份、有状态、有去重，才谈得上跨服务"))
    p.append(FIG(dia.states([
        ("已提交", "submitted", ""),
        ("处理中", "working", "受理"),
        ("需要补充信息", "input-required", "缺参数"),
        ("已完成", "completed", "补齐"),
    ], note="失败（failed）可以从任意状态跳出，是一条并列的出口；这里画的是主线。",
        tone={"idx": [2]}),
        "任务状态机：中间那个「需要补充信息」是跨 Agent 特有的"))
    p.append(SIDE("为什么 A2A 要有幂等",
                  P("跨服务的调用会因为网络原因重试。"
                    "客服侧点了「提交退款」，请求发出去了，响应却在半路上超时，"
                    "客服侧以为失败，又发了一次同样的任务。"
                    "没有幂等的话，订单侧会当成两个任务各退一笔，"
                    "用户收到双份退款，要等到对账时才发现。"),
                  P("做法是给每个任务一个唯一的 " + C("messageId") + "，"
                    "接收方保存处理过的 ID，遇到重复的直接返回上次的结果，不再执行一遍。"
                    "上面那次重试到达时带着同一个 ID，订单侧查到它已经处理过，"
                    "把上次的退款结果原样返回，钱只退一笔，客服侧也拿到了它要的响应。"),
                  P("这里有一个容易漏掉的点：" + E("去重记录和退款动作必须一起成功")
                    + "。先记 ID 再退款的话，退款失败会留下一条「已处理」的记录，"
                      "重试进来直接返回成功，钱其实没退；"
                      "先退款再记 ID，中间崩了又会重退一次。"
                      "两种顺序都在生产上出过事，做法是让两者落在同一个事务里——"
                      + E("去重记录不是一张单独的台账，它和业务副作用是一个整体") + "。")))
    p.append(P("「需要补充信息」（input-required）是 A2A 里比较特别的一个状态："
               "任务收到了，但缺一个参数，需要调用方补上。"
               "这和第 8 章的「缺参数就追问」是同一个思路，"
               "只不过从「人和系统」之间，变成了「系统和系统」之间。"))

    # ── 10.3 ──
    p.append(H3("10.3　协议细节：JSON-RPC、REST 与 SSE"))
    p.append(P(
        "这一节讲的是怎么把这套协议真正跑在 HTTP 上。先分清两种表达意图的方式。"))
    p.append(FIG(dia.compare(
        ("REST", [
            "用「网址 + 动词」表达意图",
            "GET /orders/123",
            "以资源为中心",
        ]),
        ("JSON-RPC", [
            "用「方法名 + 参数」表达意图",
            "tasks/send + 参数对象",
            "以操作为中心",
        ]),
        note="A2A 主要用后者：像「任务」这样的操作，用方法名表达比用网址更自然。"),
        "同样是远程调用，一个用网址说话，一个用方法名说话"))
    p.append(FIG(dia.cards([
        ("错误映射", "把内部的错误类型翻译成协议定义的错误码；不做，调用方拿到的错误含义不明，无法处理"),
        ("状态查询", "提供「这个任务现在怎么样了」的接口；不做，调用方只能干等或轮询"),
        ("事件流（SSE）", "长任务用流式推送进度；不做，调用方看不到进度，超时后以为失败"),
    ], cols=3, note="三件事都发生在跨服务边界上：对方看不到你的内部实现，只能靠协议里的约定判断发生了什么。"),
        "协议边界上的三件事：错误、状态、进度"))
    p.append(TRAP(P("把内部异常直接抛给调用方。内部错误信息里可能有数据库结构、文件路径这类细节，"
                    "既是安全风险，也让对方无法判断该怎么处理。"
                    "在跨服务边界上做一次错误翻译，这两件事一起解决。")))

    # ── 10.4 ──
    p.append(H3("10.4　把整条链跑通：客服 Agent 委托订单 Agent"))
    p.append(P(
        "这是全书最后一步，把前面所有东西串成一次完整的跨 Agent 调用。"))
    p.append(FIG(dia.seq(["客服 Agent", "订单 Agent"], [
        (0, 1, "提交任务：query_order + 委托上下文"),
        (1, 0, "input-required：缺 order_id", True),
        (0, 1, "补齐 order_id 后重新提交"),
        (1, 0, "completed：订单状态", True),
    ], note="同一个任务 ID 重试不会重复执行；身份靠双方各自持有的服务令牌互相验证，"
            "委托上下文里只带业务参数，不带任何凭据。"),
        "一次委托：缺参数就问，补齐再走，全程带身份"))
    p.append(CODE([
        "# 客服侧：带自己的服务令牌；上下文里只放业务参数，不放凭据",
        "ctx = DelegationContext(order_id=extracted_id)",
        "result = order_agent.invoke(task='query_order', context=ctx, token=MY_SERVICE_JWT)",
        "",
        "# 订单侧：身份从令牌里解出来，不看调用方自己怎么说",
        "caller = verify_jwt(token)                 # 验签失败直接 401",
        "assert 'order:read' in caller.scopes, '这个调用方没有读订单的权限'",
        "assert caller.tenant == ctx.tenant, '不允许跨租户委托'",
        "",
        "if not ctx.order_id:                       # 缺参数就要求补充，不猜",
        "    return TaskState(status='input-required', need=['order_id'])",
        "return TaskState(status='completed', data=authorized_reader.read(ctx.order_id))",
    ]))
    p.append(P("注意 " + C("caller") + " 是" + E("从令牌里解出来的") + "，"
               "不是调用方在请求里写的一个字符串。"
               "自己声明「我是客服」没有任何约束力——任何拿到接口地址的人都能这么写。"
               "身份要由签发方保证，接收方验签之后才认，"
               "这一点和第 6 章那句「身份不能自报」是同一条。"))
    p.append(P("这一步的验收强调三件事：" + E("鉴权链路完整") + "（每一步的身份和权限都可追溯）、"
               + E("状态可恢复") + "（任务中断后能查状态、能续）、"
               + E("失败有出口") + "（对方不可用时，客服 Agent 有降级或转人工的路径，"
                                    "而不是一直等）。"))
    p.append(KEYPOINT("跨 Agent 集成的验收标准和单体系统一样："
                      "不只看正常路径，还要看缺参、越权、对方故障这三条负向路径。"
                      "这条原则从第 6 章的最终验收一路延续到这里。"))
    p.append(SIDE("这个骨架没做什么",
                  P("这一段交付的是一个" + E("可讲、可测的企业 Agent 进阶项目骨架") + "，"
                    "它不等于「已经在生产环境跑了」。"),
                  P("没有做的部分：Kubernetes 编排、高可用发布、企业身份系统对接、"
                    "真实 GPU 容量压测、生产环境的 A2A 联调。"
                    + E("清楚地说出「我没做什么」，比含糊地暗示「我都做了」可信得多。"))))

    p.append(H4("这一章的产出物"))
    p.append(P("一个客服 Agent → 订单 Agent 的可测试企业协议集成："
               "MCP 工具鉴权与写操作审批、A2A 任务模型与幂等、"
               "HTTP 协议边界、跨 Agent 委托与失败出口。"
               "代码位置：" + C("chapters/part10-mcp-a2a-optional/10.1-10.4")
               + "，由 " + C("tools/materialize.py") + " 还原后运行。"))
    p.append(RUN([
        ("代码位置", C(".build/enterprise/<chapter>/enterprise-support/")
                      + "，由 " + C("tools/materialize.py enterprise <chapter>") + " 还原"),
        ("工作目录", "还原出来的目录"),
        ("额外依赖", "无"),
        ("执行命令", "按该目录 README 启动客服侧和订单侧两个服务"),
        ("预期输出", "一次完整委托：缺参数 → 要求补充 → 补齐 → 完成；"
                      "同一个任务 ID 重试不会重复执行"),
        ("常见失败", "身份用自报字段而不是验签；"
                      "去重记录和业务副作用不在同一个事务里"),
        ("完成证据", "越权请求被拒；缺参数返回 " + C("input-required")
                      + "，而不是猜一个值"),
    ]))
    p.append(TASK("把 10.4 里的 " + C("verify_jwt") + " 换成「直接读调用方传来的 "
                  + C("caller") + " 字段」，再用一个假的 " + C("caller")
                  + " 值发一次请求，看它是不是照单全收。"
                    "这一次实验说明的是：服务端不验签，前面所有权限设计都只是装饰。"))
    p.append(CHECKLIST([
        "MCP 与 A2A 各自解决的问题，以及两者互不替代的原因；",
        "audience / scope / 最小权限分别防住的那类越权；",
        "读工具和写工具各自的防线，以及读为什么也不能直接放行；",
        "A2A 里任务需要状态机和幂等的原因；",
        "跨服务调用做错误映射的必要性；",
        "跨 Agent 验收里三条负向路径的位置；",
        "这个项目明确没做的部分。",
    ]))

    p.append(HOOK("到这里，整条能力链走完了。但还缺一样东西——"
                  "当别人拿一个你没做过的 AI 项目给你看，"
                  "或者面试官问你「这个方案靠不靠谱」时，"
                  "你用什么标准去判断？最后一章交付的就是这套判断方法。"))
    return PAGEWRAP("10　让 Agent 之间协作：MCP 与 A2A", "".join(p))
