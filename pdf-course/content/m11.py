"""第 11 章　工具箱：怎么判断一个 AI 项目靠不靠谱"""
import dia
from comp import (P, E, C, SIDE, KEYPOINT, VERIFY, TRAP, CHECKLIST, UL, OL,
                  CODE, TABLE, HOOK, FIG, PAGEWRAP, CHAPTER, H3, H4,
                  RUN, TASK)


def chapter():
    p = []
    p.append(CHAPTER(11, "工具箱：怎么判断一个 AI 项目靠不靠谱",
                     "这一章没有新知识。它交付的是一套问题——"
                     "下次有人给你看一个 AI 项目、或者你自己要动手做一个时，"
                     "先问这几个问题。",
                     "ch11"))

    p.append(P(
        "面试的时候，大概率会被问到一个没法提前准备的问题："
        "「你觉得我们这个方案有什么问题？」",
        "反过来，自己做项目时也会遇到：某个方案看起来很有道理，"
        "但就是不确定它靠不靠谱。"))
    p.append(P(E("这一章给的不是答案，是提问的顺序。")
               + "答案会随技术更新而失效，提问的顺序不会。"))

    # ── 11.1 ──
    p.append(H3("11.1　五个问题"))
    p.append(P("这五个问题，任何一个人都能问，不需要专业背景。"
               "它们能筛掉大量看起来漂亮、实际站不住的方案。"))
    p.append(FIG(dia.cards([
        ("1　这个数字的分母是什么？", "95% 背后是 20 条样本还是 2000 条"),
        ("2　出错了会怎样？", "看得出来吗、查得到吗、最坏是什么后果"),
        ("3　它凭什么说自己对？", "结论基于什么，来源可查吗"),
        ("4　它测过吗？怎么测的？", "用例从哪来，有没有回归，负向路径"),
        ("5　换掉它，代价多大？", "模型、向量库、供应商，换一个要动多少"),
    ], cols=2),
        "五个问题：从数字、失败、依据、测试，到替换成本"))

    p.append(H4("问题一：这个数字的分母是什么？"))
    p.append(P("听到「准确率 95%」，接下来要问的是：在哪批数据上、多少条、怎么算出来的。"
               "「95%」可以来自 20 条精心挑选的样本，也可以来自 2000 条真实分布的样本，"
               "前者几乎不说明任何问题。"))
    p.append(P("能直接照着问出口的一句是："
               + E("「这 95% 是在多少条上算的？这批数据是从线上真实问题里抽的，"
                   "还是我们自己挑出来跑的？」")
               + "对方答「大概几百条」，或者要回去翻一下才知道，"
               "这个数字先记在旁边，继续往下问——它暂时撑不起任何结论。"))
    p.append(P("同类问法：" + E("「提升了 30%」是相对谁提升的？")
               + "相对上一版、相对没用这个技术的版本、还是相对人工作业的基线？"
               "没有基线的提升数字，判断不了价值。"))

    p.append(H4("问题二：出错了会怎样？"))
    p.append(P("一个系统的可靠性，不取决于它正常时多好，取决于它出错时的表现。"
               "具体看三件事：答错了用户能不能看出来，"
               "错了之后能不能追溯到是哪一步，"
               "最坏情况下会造成什么后果——是「多聊两句」还是「退错钱」。"))
    p.append(KEYPOINT("「会出错」不是缺陷，「出错时没有防线」才是。"
                      "第 6 章的拒答、第 8 章的缺参不执行、"
                      "第 10 章的写操作审批，本质都是同一件事："
                      "承认自己会错，并且为错的那一次准备出口。"))

    p.append(H4("问题三：它凭什么说自己对？"))
    p.append(P("这是第 2 章那句「证据来自你的资料、来源可以追溯」的通用版本。"
               "任何 AI 系统给出的结论，都应该能回答：这个结论基于什么？来源可查吗？"
               "如果来源变了，结论会跟着变吗？"))
    p.append(P("换成能直接问出口的一句："
               + E("「这条结论出自哪份资料的哪一段？把那一段调出来看一下。」")
               + "调得出来，就可以拿原文和结论逐句核对，错在哪一句也说得上；"
               + "调不出来、只能答「模型自己知道的」，"
               "这个系统就只能整体信或整体不信——而这两种态度都不对。"))

    p.append(H4("问题四：它测过吗？怎么测的？"))
    p.append(P("问法要具体一点，否则「我们测了」四个字就能把问题挡回来。"))
    p.append(UL([
        "测试用例是从哪来的——真实用户问题，还是自己编的？",
        "改了东西之后，怎么知道有没有变坏——有没有回归机制？",
        "有没有测过负向路径：越权、缺参、依赖故障？",
    ]))
    p.append(SIDE("为什么负向路径是关键",
                  P("正向路径的测试，只要功能能用就基本会过。"
                    "真正区分「做过测试」和「没做过测试」的，"
                    "是负向路径——那些平时不会触发、但一旦触发后果严重的情况。"
                    "这也是第 7 章整章在讲的东西。")))

    p.append(H4("问题五：换掉它，代价多大？"))
    p.append(P("一个方案是不是健康，看它有没有被锁死。"
               "模型换了要改多少代码？向量库换了要重做多少数据？"
               "供应商涨价了有没有退路？"
               "第 5 章的 Provider 抽象、第 9 章的向量库契约，都是在回答这个问题。"
               + E("能被替换的组件，才是可以放心依赖的组件。")))

    # ── 11.2 ──
    p.append(H3("11.2　红旗清单"))
    p.append(P("下面这些信号，看到任何一个都值得停下来多问一句。"
               "它们本身不一定说明项目有问题，但都是需要解释的地方。"))
    p.append(FIG(dia.cards([
        ("数字与评测", "只有准确率没有样本量；只讲用了 RAG 或 Agent，不讲怎么验证；测试全是正向路径"),
        ("安全与边界", "密钥写在代码或配置里；缓存不区分用户；权限靠调用方自报身份"),
        ("能力与容量", "什么都能答、没有拒答；宣称并发却没有压测数据；把微调当成更新知识的手段"),
    ], cols=1),
        "十条红旗大致落在三个位置：数字、安全、能力边界"))
    p.append(TABLE(
        ["看到这个", "它意味着什么"],
        [
            ["只有准确率，没有样本量和评测集说明", "这个数字大概率不可靠"],
            ["只说「用了 RAG / Agent」，不说怎么验证", "可能只有演示，没有质量判断"],
            ["没有拒答机制，什么都能答", "在拿幻觉当能力"],
            ["测试全是正向路径", "没考虑过出错，出事了没法查"],
            ["密钥写在代码或配置文件里", "基础安全习惯缺失，其他安全大概率也不到位"],
            ["「我们已经支持 100 并发」，但没压测数据", "容量是猜的，上线才知道"],
            ["缓存不区分用户", "存在跨租户数据泄露风险"],
            ["权限靠调用方自报身份", "任何人改一个字段就能冒充别人"],
            ["「微调之后模型就知道了新知识」", "混淆了微调和 RAG，方案选型可能整个错了"],
            ["反复说「效果很好」，但拿不出一个失败案例", "要么没测过，要么不愿说"],
        ],
        widths=[46, 54]))
    p.append(SIDE("怎么用这张表",
                  P("它的用途不是拿去挑别人的毛病，而是自己做项目时逐条自查。"
                    "十条里中了三条以上，先别急着加新功能，先把这些补上。"),
                  P("面试时也可以反过来用：主动说出「我这个项目在这些方面还没做到」，"
                    "比被问出来强得多——因为前者说明你知道边界在哪。")))

    # ── 11.3 ──
    p.append(H3("11.3　你自己动手时的检查清单"))
    p.append(P("上面是判断别人的。下面这八个是给你自己的——"
               "每做完一个模块，回来对一遍。"))
    p.append(FIG(dia.cards([
        ("选型（第 5 章）", "用 Prompt、RAG 还是微调，先试最便宜的"),
        ("检索（第 2 章）", "切块合理吗，换个说法还能搜到吗"),
        ("评测（第 3 章）", "评测集覆盖哪些失败模式，有拒答题吗"),
        ("Agent（第 4 章）", "循环有步数上限吗，高风险动作有人确认吗"),
        ("服务化（第 5 章）", "超时、重试、幂等、密钥位置"),
        ("产品（第 6 章）", "租户边界清楚吗，缓存键含租户和版本吗"),
        ("测试（第 7 章）", "负向路径测了吗，有拦住坏版本的闸门吗"),
        ("交付（第 9 章）", "容量有实测数据吗，知道自己没做什么吗"),
    ], cols=2),
        "八个模块，各自对应一个动手前要回答的问题"))
    p.append(KEYPOINT("整套书里最有用的一句话："
                      "能清楚说出「我不知道什么、我没做什么、我没测什么」的人，"
                      "比什么都说「没问题」的人可靠得多。"))

    p.append(RUN([
        ("代码位置", "无——这一章不涉及代码"),
        ("工作目录", "不适用"),
        ("额外依赖", "无"),
        ("执行命令", "不适用"),
        ("预期输出", "不适用"),
        ("常见失败", "不适用"),
        ("完成证据", "能对任意一个 AI 项目方案，按 11.1 的五个问题各问一句，"
                      "并判断对方的回答是「说清了」还是「绕过去了」"),
    ]))
    p.append(TASK("找一份你自己以前做过的项目说明，或者任意一个 AI 产品的介绍，"
                  "用 11.1 那五个问题逐条问一遍，把答不上来的地方记下来。"
                  "那份记录就是你现在最该补的清单。"))
    p.append(HOOK("回到序章那句话：这本书脱胎于一份回答「AI 客服答错了你怎么测」的记录。"
                  "现在这个问题有了完整的答案——四个出错位置、三层测试、"
                  "一道能拦住坏版本的门，以及一整套「我不确定的时候会怎么办」。"
                  "这就是全书真正交付的东西。"))
    return PAGEWRAP("11　工具箱：怎么判断一个 AI 项目靠不靠谱", "".join(p))
